#!/usr/bin/env node
'use strict';

const fs = require('node:fs');
const path = require('node:path');

const ATHLETE_COUNT = 1000;
const RANDOM_SEED = 20261023;
const SURNAMES = [
  '王', '李', '张', '刘', '陈', '杨', '黄', '赵', '周', '吴',
  '徐', '孙', '马', '朱', '胡', '林', '郭', '何', '高', '罗',
];
const GIVEN_NAMES = [
  '浩然', '欣怡', '子轩', '雨桐', '明阳', '思琪', '俊豪', '诗涵',
  '梓豪', '雨欣', '子涵', '梦瑶', '锦程', '诗雅', '子睿', '嘉欣',
  '俊宇', '语桐', '文博', '雨萱', '子杰', '艺涵', '浩宇', '欣妍',
  '晨曦', '佳宁', '宇航', '可心', '博文', '一诺',
];

function createRandom(seed) {
  let state = seed >>> 0;
  return () => {
    state = (state * 1664525 + 1013904223) >>> 0;
    return state / 0x100000000;
  };
}

function generateAthletes(count = ATHLETE_COUNT, seed = RANDOM_SEED) {
  if (!Number.isInteger(count) || count < 0) {
    throw new RangeError('运动员数量必须是非负整数');
  }

  const random = createRandom(seed);
  const classSequences = new Map();
  return Array.from({ length: count }, (_, index) => {
    const id = index + 1;
    const grade = (index % 6) + 1;
    const gender = random() < 0.5 ? 'male' : 'female';
    const surname = SURNAMES[Math.floor(random() * SURNAMES.length)];
    const givenName = GIVEN_NAMES[Math.floor(random() * GIVEN_NAMES.length)];
    const classNumber = (Math.floor(index / 6) % 8) + 1;
    const classKey = `${grade}-${classNumber}`;
    const classSequence = (classSequences.get(classKey) || 0) + 1;
    classSequences.set(classKey, classSequence);

    return {
      id,
      student_no: `SM${String(id).padStart(6, '0')}`,
      bib_number: `${grade}${String(classNumber).padStart(2, '0')}${String(classSequence).padStart(2, '0')}`,
      name: surname + givenName,
      class_name: `${classNumber}班`,
      grade,
      gender,
    };
  });
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function createSeedSql(athletes) {
  const rows = athletes.map(athlete => `  (${[
    athlete.id,
    sqlString(athlete.student_no),
    sqlString(athlete.bib_number),
    sqlString(athlete.name),
    sqlString(athlete.class_name),
    athlete.grade,
    sqlString(athlete.gender),
  ].join(', ')})`);

  return [
    '-- Generated by seed.js. Re-running replaces the athlete table contents.',
    'PRAGMA foreign_keys = ON;',
    'BEGIN TRANSACTION;',
    'DELETE FROM athlete;',
    'INSERT INTO athlete (id, student_no, bib_number, name, class_name, grade, gender)',
    'VALUES',
    rows.join(',\n') + ';',
    'COMMIT;',
    '',
  ].join('\n');
}

function main() {
  const outputPath = path.join(__dirname, 'seed-athletes.sql');
  const athletes = generateAthletes();
  fs.writeFileSync(outputPath, createSeedSql(athletes), 'utf8');
  console.log(`已生成 ${athletes.length} 条运动员数据：${outputPath}`);
}

if (require.main === module) {
  main();
}

module.exports = { generateAthletes, createSeedSql };
